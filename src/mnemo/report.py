"""Render results.json into RESULTS.md and figures. Numbers are never typed by hand."""

from __future__ import annotations

from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt

SYSTEMS = ("store-all", "rule-based", "untrained-policy", "mnemo-ppo", "oracle")
COLORS = {
    "store-all": "#9b9b9b",
    "rule-based": "#d08a2e",
    "untrained-policy": "#c9a0dc",
    "mnemo-ppo": "#2a6fdb",
    "oracle": "#2f9e6e",
    "random": "#cccccc",
}
COLS = [
    ("state_f1", "State F1 ↑", 3),
    ("retention", "Retention ↑", 3),
    ("precision", "Precision ↑", 3),
    ("stale_rate", "Stale ↓", 3),
    ("junk_rate", "Junk ↓", 3),
    ("contradiction_rate", "Contradiction ↓", 3),
    ("avg_tokens", "Avg tokens ↓", 1),
    ("qa_accuracy", "QA acc ↑", 3),
    ("harmful_deletions", "Harmful del. ↓", 2),
]


def _cell(s: dict, nd: int) -> str:
    return f"{s['mean']:.{nd}f} [{s['lo']:.{nd}f}, {s['hi']:.{nd}f}]"


def _table(stats: dict, systems=SYSTEMS) -> str:
    head = "| System | " + " | ".join(c[1] for c in COLS) + " |"
    sep = "|---|" + "---|" * len(COLS)
    rows = [head, sep]
    for s in systems:
        if s in stats:
            rows.append(f"| **{s}** | " + " | ".join(_cell(stats[s][k], nd) for k, _, nd in COLS) + " |")
    return "\n".join(rows)


def _diff_table(diffs: dict) -> str:
    keys = ("state_f1", "qa_accuracy", "stale_rate", "avg_tokens", "harmful_deletions")
    rows = ["| Comparison | " + " | ".join(keys) + " |", "|---|" + "---|" * len(keys)]
    for name, d in diffs.items():
        cells = []
        for k in keys:
            x = d[k]
            sig = "" if x["lo"] <= 0 <= x["hi"] else " *"
            cells.append(f"{x['mean']:+.3f} [{x['lo']:+.3f}, {x['hi']:+.3f}]{sig}")
        rows.append(f"| {name} | " + " | ".join(cells) + " |")
    return "\n".join(rows)


def write_report(res: dict, out: Path) -> None:
    out.mkdir(parents=True, exist_ok=True)
    m = res["meta"]
    lines = [
        "# MNEMO — Experimental Results",
        "",
        f"_Generated by `mnemo evaluate` (config `{m['config_fingerprint']}`; "
        f"{m['n_test']} test episodes, {m['n_ood']} OOD episodes; PPO seeds: {', '.join(m['ppo_models'])}; "
        f"default budget {m['budget_tokens']} tokens)._ "
        "Values are mean [95% bootstrap CI over episodes]. `mnemo-ppo` is the per-episode mean over the "
        "independently trained seeds. `oracle` reads hidden ground truth and is a one-step ceiling, not a "
        "deployable system.",
        "",
        "## 1. Held-out test split",
        "",
        _table(res["test"]),
        "",
        "### Paired differences, MNEMO-PPO minus reference (`*` = 95% CI excludes 0)",
        "",
        _diff_table(res["paired_diffs_test"]),
        "",
        "## 2. Distribution-shifted split (adversarial/noisy profile mix, unseen in training)",
        "",
        _table(res["ood"]),
        "",
        _diff_table(res["paired_diffs_ood"]),
        "",
        "## 3. Per-seed test results",
        "",
        _table(res["test"], [s for s in res["test"] if s.startswith("mnemo-ppo[")]),
        "",
        "## 4. Ablations (single seed, 400k steps vs 800k for the main runs)",
        "",
        "Ablated runs trained for half as many steps as the main seeds (validation return had largely "
        "plateaued by 400k), so differences smaller than the seed-to-seed spread in section 3 are not "
        "interpretable.",
        "",
        _table(res["ablations_test"], list(res["ablations_test"])) if res["ablations_test"] else "_not run_",
        "",
        "## 5. Robustness sweeps",
        "",
    ]
    for axis, label in (("noise", "Extractor-noise multiplier (1.0 = training mean)"), ("budget", "Token budget")):
        lines += [
            f"### {label}",
            "",
            "| Value | "
            + " | ".join(f"{s} F1 / QA" for s in ("store-all", "rule-based", "mnemo-ppo", "oracle"))
            + " |",
            "|---|---|---|---|---|",
        ]
        for v, row in res["sweeps"][axis].items():
            lines.append(
                f"| {v} | "
                + " | ".join(
                    f"{row[s]['state_f1']:.3f} / {row[s]['qa_accuracy']:.3f}"
                    for s in ("store-all", "rule-based", "mnemo-ppo", "oracle")
                )
                + " |"
            )
        lines.append("")
    lines += [
        "## 6. Policy behaviour (action counts over the test split)",
        "",
        "| System | ADD | UPDATE | IGNORE | DELETE |",
        "|---|---|---|---|---|",
    ]
    for s in SYSTEMS:
        c = res["action_counts_test"].get(s)
        if c:
            lines.append(f"| {s} | {c['ADD']} | {c['UPDATE']} | {c['IGNORE']} | {c['DELETE']} |")
    lines += [
        "",
        "## 7. QA accuracy by question type (test)",
        "",
        "| System | " + " | ".join(sorted({k for v in res["qa_by_kind_test"].values() for k in v})) + " |",
    ]
    kinds = sorted({k for v in res["qa_by_kind_test"].values() for k in v})
    lines.append("|---|" + "---|" * len(kinds))
    for s, v in res["qa_by_kind_test"].items():
        lines.append(f"| {s} | " + " | ".join(f"{v.get(k, float('nan')):.3f}" for k in kinds) + " |")
    lines += [
        "",
        "## 8. Rule-based baseline tuning",
        "",
        f"Confidence thresholds tuned on validation episodes: `{m['rule_thresholds']}`.",
        "",
    ]
    (out / "RESULTS.md").write_text("\n".join(lines))
    _plots(res, out)


def _plots(res: dict, out: Path) -> None:
    plt.rcParams.update({"font.size": 10, "axes.spines.top": False, "axes.spines.right": False})
    fig, axes = plt.subplots(1, 4, figsize=(15, 3.6))
    for ax, (k, title) in zip(
        axes,
        [
            ("state_f1", "State F1 ↑"),
            ("qa_accuracy", "QA accuracy ↑"),
            ("stale_rate", "Stale rate ↓"),
            ("avg_tokens", "Avg memory tokens ↓"),
        ],
        strict=True,
    ):
        sys_ = [s for s in SYSTEMS if s in res["test"]]
        means = [res["test"][s][k]["mean"] for s in sys_]
        err = [
            [res["test"][s][k]["mean"] - res["test"][s][k]["lo"] for s in sys_],
            [res["test"][s][k]["hi"] - res["test"][s][k]["mean"] for s in sys_],
        ]
        ax.bar(range(len(sys_)), means, yerr=err, color=[COLORS[s] for s in sys_], capsize=3)
        ax.set_xticks(
            range(len(sys_)), [s.replace("-policy", "").replace("mnemo-", "") for s in sys_], rotation=30, ha="right"
        )
        ax.set_title(title)
    fig.tight_layout()
    fig.savefig(out / "fig_main.png", dpi=150)
    plt.close(fig)

    fig, axes = plt.subplots(1, 4, figsize=(15, 3.6))
    for col, (axis, xlabel) in enumerate((("noise", "extractor-noise multiplier"), ("budget", "token budget"))):
        xs = list(res["sweeps"][axis])
        for j, (k, yl) in enumerate((("state_f1", "State F1"), ("qa_accuracy", "QA accuracy"))):
            ax = axes[col * 2 + j]
            for s in ("store-all", "rule-based", "mnemo-ppo", "oracle"):
                ax.plot(xs, [res["sweeps"][axis][x][s][k] for x in xs], marker="o", label=s, color=COLORS[s])
            ax.set_xlabel(xlabel)
            ax.set_ylabel(yl)
    axes[0].legend(frameon=False, fontsize=8)
    fig.tight_layout()
    fig.savefig(out / "fig_sweeps.png", dpi=150)
    plt.close(fig)

    if res["training"]:
        fig, ax = plt.subplots(figsize=(5.5, 3.4))
        for name, meta in res["training"].items():
            ax.plot([h["timesteps"] for h in meta["history"]], [h["val_return"] for h in meta["history"]], label=name)
        ax.set_xlabel("timesteps")
        ax.set_ylabel("validation return")
        ax.legend(frameon=False)
        fig.tight_layout()
        fig.savefig(out / "fig_training.png", dpi=150)
        plt.close(fig)
